USE fazhitong;

CREATE TABLE IF NOT EXISTS `regulation` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `title` VARCHAR(256) NOT NULL COMMENT '标题',
    `law_type` VARCHAR(64) DEFAULT NULL COMMENT '类型',
    `issuing_authority` VARCHAR(128) DEFAULT NULL COMMENT '制定机关',
    `publish_date` VARCHAR(32) DEFAULT NULL COMMENT '发布日期',
    `effective_date` VARCHAR(32) DEFAULT NULL COMMENT '施行日期',
    `status` VARCHAR(32) DEFAULT '现行有效' COMMENT '效力状态',
    `content` LONGTEXT COMMENT '内容摘要',
    `keywords` VARCHAR(256) DEFAULT NULL COMMENT '关键词',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_title (`title`),
    INDEX idx_law_type (`law_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='法律法规';

