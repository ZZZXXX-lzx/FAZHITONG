def gen_sql():
    sql = ""  # 用多条 INSERT 便于问题定位
    for idx, c in enumerate(CASES, start=1):
        (cause_name, court_name, case_year, judgment_result, keywords,
         abstract, focus_points, judgment_basis, full_text) = [str(x) for x in c]
        def esc(s):
            return s.replace("\\", "\\\\").replace("'", "''")
        vals = (esc(cause_name), esc(court_name), esc(case_year),
                esc(judgment_result), esc(keywords), esc(abstract),
                esc(focus_points), esc(judgment_basis), esc(full_text))
        sql += ("INSERT INTO `case_government` "
                "(`cause_name`,`court_name`,`case_year`,`judgment_result`,`keywords`,"
                "`abstract`,`focus_points`,`judgment_basis`,`full_text`,`source`,`status`) "
                "VALUES ('%s','%s','%s','%s','%s','%s','%s','%s','%s','SEED_REF',1);\n"
                % vals)
    return sql


def main():
    sql_text = "USE fazhitong;\nSET NAMES utf8mb4;\n" + gen_sql()
    proc = subprocess.run([MYSQL, "-uroot", "-p123456"],
                          input=sql_text.encode("utf-8"),
                          capture_output=True)
    if proc.returncode != 0:
        print("导入失败:")
        print(proc.stderr.decode("utf-8", "ignore"))
        raise SystemExit(1)
    chk = subprocess.run([MYSQL, "-uroot", "-p123456", "-N", "-e",
                          "SELECT COUNT(*) FROM fazhitong.case_government;"],
                         capture_output=True)
    print("导入完成，当前案例总数:", chk.stdout.decode("utf-8", "ignore").strip())


if __name__ == "__main__":
    main()